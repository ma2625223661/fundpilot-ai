// Ports the pure-logic part of the old frontend (../dist/*.js) into ES modules
// under src/lib/legacy, verbatim, and points the old frontend tests at them.
// Re-run whenever the old frontend logic changes during the migration:
//   npm run port:legacy
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(web, '..');
const dist = path.join(root, 'dist');
const outDir = path.join(web, 'src/lib/legacy');
const testDir = path.join(web, 'tests/legacy');

// Files whose leading section is pure logic, cut where the old code exports it.
const MODULES = [
  'sector-scarcity.js',
  'sector-research.js',
  'sector-history.js',
  'ai-subscription.js',
  'research-review.js',
  'research-cycle.js',
];

function port(name) {
  const source = fs.readFileSync(path.join(dist, name), 'utf8').replace(/\r\n/g, '\n');
  const lines = source.split('\n');
  const opener = lines.findIndex(l => /^\(function ?\(root\) ?\{/.test(l.trim()));
  if (opener < 0) throw new Error(`${name}: IIFE opener not found`);
  let start = opener + 1;
  if (/^'use strict';$/.test(lines[start].trim())) start += 1;
  const end = lines.findIndex((l, i) => i >= start && /const api ?= ?\{|module\.exports ?= ?\{/.test(l));
  if (end < 0) throw new Error(`${name}: export point not found`);
  const cut = lines[end];
  const literal = (cut.match(/const api ?= ?(\{[^}]*\})/) || cut.match(/module\.exports ?= ?(\{[^}]*\})/) || [])[1];
  if (!literal) throw new Error(`${name}: export object not found`);
  const names = literal.slice(1, -1).split(',').map(s => s.trim()).filter(Boolean);
  if (names.some(n => !/^[A-Za-z_$][\w$]*$/.test(n))) throw new Error(`${name}: non-shorthand export`);
  let body = lines.slice(start, end).join('\n');
  let header = '';
  if (name === 'sector-research.js') {
    const before = body;
    body = body.replace(/const scarcityUI = [^;]*;/, 'const scarcityUI = scarcityModule;');
    if (body === before) throw new Error(`${name}: scarcity import not found`);
    header = "import scarcityModule from './sector-scarcity.js';\n";
  }
  if (/\b(require|module)\s*[.(]/.test(body)) throw new Error(`${name}: CommonJS left in ported body`);
  const out = [
    `// Generated by scripts/port-legacy.mjs from dist/${name}. Do not edit by hand.`,
    '// Logic is copied verbatim from the old frontend; only the module wrapper changed.',
    '/* eslint-disable */',
    '// @ts-nocheck',
    header + 'const root = globalThis;',
    body,
    `const api = ${literal};`,
    'export default api;',
    `export { ${names.join(', ')} };`,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, name), out);
  return names.length;
}

function portTests() {
  const rewrite = (text, depth) => text
    .replace(/require\((['"])\.{1,2}\/dist\/([\w-]+\.js)\1\)/g, (_, q, f) =>
      MODULES.includes(f) ? `require(${q}${depth}src/lib/legacy/${f}${q})` : _)
    .replace(/require\((['"])\.\/test_helpers\/([\w-]+\.cjs)\1\)/g, "require($1./helpers/$2$1)")
    .replace(/path\.join\(__dirname,\s*(['"])(\.\.\/)?dist\//g, (_, q, up) =>
      `path.join(__dirname,${q}${up ? '../../../../' : '../../../'}dist/`);
  let count = 0;
  for (const file of fs.readdirSync(root).filter(f => /^test_.*\.cjs$/.test(f))) {
    const text = fs.readFileSync(path.join(root, file), 'utf8');
    fs.writeFileSync(path.join(testDir, file), rewrite(text, '../../'));
    count += 1;
  }
  for (const file of fs.readdirSync(path.join(root, 'test_helpers')).filter(f => f.endsWith('.cjs'))) {
    const text = fs.readFileSync(path.join(root, 'test_helpers', file), 'utf8');
    fs.writeFileSync(path.join(testDir, 'helpers', file), rewrite(text, '../../../'));
  }
  return count;
}

fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(path.join(testDir, 'helpers'), { recursive: true });
for (const name of MODULES) console.log(`ported ${name}: ${port(name)} exports`);
console.log(`copied ${portTests()} legacy test files`);
